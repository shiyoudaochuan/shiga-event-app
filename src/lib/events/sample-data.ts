function daysFromNow(days: number, hour: number, minute = 0): string {
  // 日本時間の hour:minute を UTC に直して ISO 文字列にする（JST = UTC+9）
  const now = new Date();
  const d = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + days, hour - 9, minute));
  return d.toISOString();
}

function todayIso(): string {
  return new Date().toISOString().slice(0, 10);
}

